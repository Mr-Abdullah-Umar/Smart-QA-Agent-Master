"""Pytest runner orchestrating sandboxed test execution, retries, and evidence capture.

Enforces Section 8.9 specifications:
- Dispatches pytest via SandboxedSubprocess.
- Produces results.json and junit.xml in the run results folder.
- Flags retried passing tests as flaky (never converting them to clean passes).
- Secret values are injected only as environment variables and masked in every artifact.
"""

import json
import logging
import re
import sys
from pathlib import Path
from typing import Callable, Dict, Iterable, List, Optional

import defusedxml.ElementTree as ET
from pydantic import BaseModel, Field

from qa_engine.execution.sandbox import SandboxedSubprocess
from qa_engine.generation.testcases import TEST_TYPES
from qa_engine.orchestrator.run_store import RunStore

logger = logging.getLogger(__name__)

SECRET_MASK = "[MASKED-SECRET]"  # noqa: S105 - replacement marker, not a credential

# Engine-owned conftest placed next to generated scripts. It registers markers, records the
# approved test case ID in junit.xml (traceability to Gate 1), keeps navigation inside the
# confirmed domain scope, and resolves {{secret.NAME}} / {{unique}} placeholders at run time.
HARNESS_CONFTEST = '''"""Harness-managed pytest configuration (generated by the QA engine)."""
import json
import os
import re
import secrets
import time
from urllib.parse import urljoin, urlparse

import pytest

_PLACEHOLDER = re.compile(r"\\{\\{\\s*(secret\\.([A-Za-z0-9_]+)|unique)\\s*\\}\\}")
_TEST_TYPES = %(test_types)r


def pytest_configure(config):
    config.addinivalue_line("markers", "tc(tc_id): approved test case identifier")
    for name in _TEST_TYPES:
        config.addinivalue_line("markers", f"{name}: {name} test")


@pytest.fixture(autouse=True)
def _harness_record_tc_id(request, record_property):
    marker = request.node.get_closest_marker("tc")
    if marker and marker.args:
        record_property("tc_id", str(marker.args[0]))


def _host_allowed(host):
    domains = [d.strip().lower() for d in os.environ.get("QA_ALLOWED_DOMAINS", "").split(",")]
    domains = [d for d in domains if d]
    host = (host or "").lower()
    return any(host == d or host.endswith("." + d) for d in domains)


def _origin_map():
    try:
        mapping = json.loads(os.environ.get("QA_ORIGIN_MAP") or "{}")
    except ValueError:
        return {}
    return {str(k).rstrip("/"): str(v).rstrip("/") for k, v in mapping.items()}


def _map_origin(url, mapping):
    for source, target in mapping.items():
        if url == source or url.startswith(source + "/") or url.startswith(source + "?"):
            return target + url[len(source):]
    return url


@pytest.fixture
def harness_url(base_url):
    mapping = _origin_map()

    def resolve(target=""):
        url = urljoin(base_url, _map_origin(target, mapping)) if target else base_url
        if not _host_allowed(urlparse(url).hostname):
            pytest.fail(f"Navigation to {url} is outside the confirmed scope.")
        return url

    def match(expected):
        """Expected URL fragment, moved to the environment under test."""
        expected = _map_origin(expected, mapping)
        for source, target in mapping.items():
            source_host, target_host = urlparse(source).netloc, urlparse(target).netloc
            if source_host and (expected == source_host or expected.startswith(source_host + "/")):
                return target_host + expected[len(source_host):]
        return expected

    resolve.match = match
    return resolve


@pytest.fixture
def harness_text():
    unique = f"{int(time.time())}{secrets.token_hex(2)}"

    def expand(text):
        def repl(match):
            if match.group(1) == "unique":
                return unique
            name = match.group(2).upper()
            value = os.environ.get(f"QA_SECRET_{name}")
            if value is None:
                pytest.skip(f"BLOCKED: secret '{name}' is not configured for this suite.")
            return value

        return _PLACEHOLDER.sub(repl, text)

    return expand
''' % {"test_types": TEST_TYPES}

_PARAM_SUFFIX = re.compile(r"\[.*\]$")


class TestCaseOutcome(BaseModel):
    __test__ = False
    tc_id: str
    status: str  # "passed", "failed", "flaky", "blocked", "skipped"
    duration_seconds: float = 0.0
    error_message: Optional[str] = None
    stack_trace: Optional[str] = None
    evidence_ids: List[str] = Field(default_factory=list)


class ExecutionSummary(BaseModel):
    total_tests: int = 0
    passed: int = 0
    failed: int = 0
    flaky: int = 0
    blocked: int = 0
    skipped: int = 0
    duration_seconds: float = 0.0
    outcomes: List[TestCaseOutcome] = Field(default_factory=list)


class SecretMasker:
    """Replaces known secret values with a fixed mask."""

    def __init__(self, values: Optional[Iterable[str]] = None):
        self.values = sorted({v for v in (values or []) if v and len(v) >= 3}, key=len)[::-1]

    def __call__(self, text: Optional[str]) -> Optional[str]:
        if not text or not self.values:
            return text
        for value in self.values:
            text = text.replace(value, SECRET_MASK)
        return text


class PytestRunner:
    """Executes generated pytest suites inside the sandboxed environment."""

    def __init__(self, run_store: RunStore, python_executable: Optional[str] = None):
        self.store = run_store
        self.python_exe = python_executable or sys.executable

    @staticmethod
    def ensure_conftest(scripts_dir: Path) -> Path:
        """Write the harness conftest that registers markers and records TC IDs."""
        scripts_dir.mkdir(parents=True, exist_ok=True)
        conftest = scripts_dir / "conftest.py"
        conftest.write_text(HARNESS_CONFTEST, encoding="utf-8")
        return conftest

    def run_tests(
        self,
        test_dir: Path,
        base_url: str,
        retries: int = 1,
        timeout_seconds: int = 300,
        headed: bool = False,
        browser_channel: Optional[str] = None,
        slowmo_ms: int = 0,
        on_output: Optional[Callable[[str], None]] = None,
        allowed_domains: Optional[List[str]] = None,
        secrets: Optional[Dict[str, str]] = None,
        select_tests: Optional[List[str]] = None,
        marker: Optional[str] = None,
        origin_map: Optional[Dict[str, str]] = None,
    ) -> ExecutionSummary:
        results_dir = self.store.run_dir / "results"
        results_dir.mkdir(parents=True, exist_ok=True)
        junit_xml = results_dir / "junit.xml"
        scripts_dir = test_dir.parent
        self.ensure_conftest(scripts_dir)
        masker = SecretMasker((secrets or {}).values())

        args = [
            self.python_exe,
            "-m",
            "pytest",
            str(test_dir),
            "-v",
            "--tb=short",
            "-p",
            "no:asyncio",
            "-W",
            "ignore::DeprecationWarning",
            "-o",
            "junit_family=xunit1",
            f"--base-url={base_url}",
        ]
        if headed:
            args.append("--headed")
        if browser_channel:
            args.append(f"--browser-channel={browser_channel}")
        if slowmo_ms > 0:
            args.append(f"--slowmo={slowmo_ms}")
        if select_tests:
            args.extend(["-k", " or ".join(select_tests)])
        if marker:
            args.extend(["-m", marker])

        extra_env = {
            "PYTHONPATH": str(scripts_dir),
            "PYTHONUNBUFFERED": "1",
            "PYTHONUTF8": "1",
            "QA_ALLOWED_DOMAINS": ",".join(allowed_domains or []),
            "QA_ORIGIN_MAP": json.dumps(origin_map or {}),
        }
        for name, value in (secrets or {}).items():
            extra_env[f"QA_SECRET_{name.upper()}"] = value

        def emit(line: str) -> None:
            if on_output:
                on_output(masker(line) or "")

        code, stdout, stderr = SandboxedSubprocess.run_sandboxed(
            args=args + [f"--junitxml={junit_xml}"],
            cwd=self.store.run_dir,
            timeout_seconds=timeout_seconds,
            extra_env=extra_env,
            on_output=emit,
        )
        self.store.write_atomic("evidence/logs/pytest_output.log", masker(stdout + stderr) or "")
        self._mask_file(junit_xml, masker)

        summary = self._parse_junit_xml(junit_xml)
        if summary.total_tests == 0 and code != 0:
            logger.warning("Pytest produced no results (exit %s): %s", code, stderr.strip())
            if code == 5:
                emit("No tests matched the selection.")

        if summary.failed > 0 and retries > 0:
            self._execute_retries(args, extra_env, summary, timeout_seconds, emit, masker)

        self.store.write_json_atomic("results/results.json", summary.model_dump())
        self.store.audit.log_event(
            stage="STAGE_8_EXECUTION",
            event_type="TEST_EXECUTION_COMPLETED",
            actor="engine",
            details={
                "total": summary.total_tests,
                "passed": summary.passed,
                "failed": summary.failed,
                "flaky": summary.flaky,
                "blocked": summary.blocked,
            },
        )
        return summary

    @staticmethod
    def _mask_file(path: Path, masker: SecretMasker) -> None:
        if masker.values and path.exists():
            path.write_text(masker(path.read_text(encoding="utf-8")) or "", encoding="utf-8")

    def _execute_retries(
        self,
        args: List[str],
        extra_env: Dict[str, str],
        summary: ExecutionSummary,
        timeout_seconds: int,
        emit: Callable[[str], None],
        masker: SecretMasker,
    ) -> None:
        """Re-run only the failed tests; any that now pass are flagged flaky (never passed)."""
        retry_xml = self.store.run_dir / "results" / "junit-retry.xml"
        emit("Retrying failed test(s) once to detect flakiness ...")
        SandboxedSubprocess.run_sandboxed(
            args=args + ["--last-failed", f"--junitxml={retry_xml}"],
            cwd=self.store.run_dir,
            timeout_seconds=timeout_seconds,
            extra_env=extra_env,
            on_output=emit,
        )
        self._mask_file(retry_xml, masker)
        retry_summary = self._parse_junit_xml(retry_xml)
        passed_on_retry = {o.tc_id for o in retry_summary.outcomes if o.status == "passed"}

        for outcome in summary.outcomes:
            if outcome.status == "failed" and outcome.tc_id in passed_on_retry:
                outcome.status = "flaky"
                summary.failed -= 1
                summary.flaky += 1

    @staticmethod
    def _tc_id_for_case(case) -> str:
        """Resolve the approved TC ID recorded by the harness conftest, else derive from name."""
        props = case.find("properties")
        if props is not None:
            for prop in props.findall("property"):
                if prop.get("name") == "tc_id" and prop.get("value"):
                    return prop.get("value")
        name = _PARAM_SUFFIX.sub("", case.get("name", "unknown"))
        if name.startswith("test_"):
            name = name[len("test_") :]
        return name.upper().replace("_", "-")

    def _parse_junit_xml(self, junit_path: Path, raw_stdout: str = "") -> ExecutionSummary:
        """Parse JUnit XML into an execution summary."""
        summary = ExecutionSummary()
        if not junit_path.exists():
            return summary

        try:
            tree = ET.parse(junit_path)
            root = tree.getroot()

            suites = [root] if root.tag == "testsuite" else list(root.findall("testsuite"))
            for suite in suites:
                summary.duration_seconds += float(suite.get("time", 0.0))

                for case in suite.findall("testcase"):
                    # Element truthiness reflects child count, so compare against None.
                    failure_node = case.find("failure")
                    if failure_node is None:
                        failure_node = case.find("error")
                    skipped_node = case.find("skipped")
                    message = None
                    trace = None

                    if failure_node is not None:
                        status = "failed"
                        summary.failed += 1
                        message, trace = failure_node.get("message"), failure_node.text
                    elif skipped_node is not None:
                        message = skipped_node.get("message") or ""
                        if "BLOCKED" in message:
                            status = "blocked"
                            summary.blocked += 1
                        else:
                            status = "skipped"
                            summary.skipped += 1
                    else:
                        status = "passed"
                        summary.passed += 1
                    summary.total_tests += 1

                    summary.outcomes.append(
                        TestCaseOutcome(
                            tc_id=self._tc_id_for_case(case),
                            status=status,
                            duration_seconds=float(case.get("time", 0.0)),
                            error_message=message,
                            stack_trace=trace,
                        )
                    )
        except Exception as exc:
            logger.warning("Failed to parse JUnit XML report at %s: %s", junit_path, exc)

        return summary
